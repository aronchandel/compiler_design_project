"""AST-to-Python code generator (Phase 1 bootstrap path)."""

from __future__ import annotations

from typing import TYPE_CHECKING

import cpp2py
from cpp2py.diagnostics import DiagnosticSink, Diagnostic, Severity
from cpp2py.frontend import ast_nodes as ast
from cpp2py.codegen.names import NameMangler
from cpp2py.codegen.pyexpr import render_expr

if TYPE_CHECKING:
    from cpp2py.semantics.symbols import SemanticInfo


def generate(program: ast.Program, info: SemanticInfo,
             sink: DiagnosticSink) -> str | None:
    """Generate Python source from the AST. Returns None on error."""
    gen = _Generator(program, info, sink)
    return gen.run()


class _Generator:
    def __init__(self, program: ast.Program, info: SemanticInfo,
                 sink: DiagnosticSink) -> None:
        self._program = program
        self._info = info
        self._sink = sink
        self._mangler = NameMangler()
        self._lines: list[str] = []
        self._warnings: list[Diagnostic] = []
        self._uses_input = False
        self._indent = ""

    def run(self) -> str | None:
        # First pass: scan for input usage and collect all variable names
        self._scan_program(self._program)

        # Generate header
        header_line = f"# Generated by cpp2py {cpp2py.__version__} (naive integer semantics: no overflow modelling)"
        self._lines.append(header_line)

        # Collect W6001 warnings from the scan
        for w in self._warnings:
            span = w.span
            if span is not None:
                comment = f"# WARNING {w.code} {span.start.line}:{span.start.col}: {w.message}"
            else:
                comment = f"# WARNING {w.code}: {w.message}"
            self._lines.append(comment)
            # Also emit to diagnostic sink
            self._sink.warning(w.code, w.message, w.span)

        self._lines.append("import sys")

        if self._uses_input:
            self._lines.append("_tokens = iter(sys.stdin.read().split())")

        self._lines.append("")
        self._lines.append("")

        # Generate main function
        for func in self._program.functions:
            self._gen_function(func)

        self._lines.append("")
        self._lines.append("")
        self._lines.append('if __name__ == "__main__":')
        self._lines.append("    sys.exit(main())")
        self._lines.append("")  # trailing newline

        result = '\n'.join(self._lines)

        # Self-check with compile()
        try:
            compile(result, "<generated>", "exec")
        except SyntaxError as e:
            self._sink.error("E9001", f"internal error: generated Python failed compile(): {e}", None)
            return None

        return result

    def _scan_program(self, program: ast.Program) -> None:
        """Scan for input usage and div/mod warnings."""
        for func in program.functions:
            for stmt in func.body.statements:
                self._scan_stmt(stmt)

    def _scan_stmt(self, stmt: ast.Stmt) -> None:
        if isinstance(stmt, ast.InputStmt):
            self._uses_input = True
        elif isinstance(stmt, ast.DeclStmt):
            for decl in stmt.declarators:
                # Pre-register variable names for mangling
                self._mangler.mangle(decl.name)
                if decl.init is not None:
                    self._scan_expr(decl.init)
        elif isinstance(stmt, ast.AssignStmt):
            self._scan_expr(stmt.value)
        elif isinstance(stmt, ast.OutputStmt):
            for item in stmt.items:
                if isinstance(item, (ast.StringLiteral, ast.EndlMarker)):
                    continue
                self._scan_expr(item)
        elif isinstance(stmt, ast.ReturnStmt):
            if stmt.value is not None:
                self._scan_expr(stmt.value)

    def _scan_expr(self, expr: ast.Expr) -> None:
        if isinstance(expr, ast.BinaryExpr):
            if expr.op == '/':
                w = Diagnostic(
                    Severity.WARNING, "W6001",
                    "'/' is emitted as Python floor division; the result differs from C++ when an operand is negative",
                    expr.span)
                self._warnings.append(w)
            elif expr.op == '%':
                w = Diagnostic(
                    Severity.WARNING, "W6001",
                    "'%' is emitted as Python remainder; the result differs from C++ when an operand is negative",
                    expr.span)
                self._warnings.append(w)
            self._scan_expr(expr.left)
            self._scan_expr(expr.right)
        elif isinstance(expr, ast.UnaryExpr):
            self._scan_expr(expr.operand)

    def _gen_function(self, func: ast.FunctionDef) -> None:
        self._lines.append(f"def {func.name}():")
        self._indent = "    "

        stmts = func.body.statements
        has_body = False

        for stmt in stmts:
            if isinstance(stmt, ast.ReturnStmt):
                # Always emit return 0 at the end
                self._lines.append(f"{self._indent}return 0")
                has_body = True
            else:
                self._gen_stmt(stmt)
                has_body = True

        if not has_body:
            self._lines.append(f"{self._indent}return 0")

        # If there's no explicit return 0, add one
        if stmts and not isinstance(stmts[-1], ast.ReturnStmt):
            self._lines.append(f"{self._indent}return 0")

        self._indent = ""

    def _gen_stmt(self, stmt: ast.Stmt) -> None:
        if isinstance(stmt, ast.DeclStmt):
            self._gen_decl(stmt)
        elif isinstance(stmt, ast.AssignStmt):
            self._gen_assign(stmt)
        elif isinstance(stmt, ast.InputStmt):
            self._gen_input(stmt)
        elif isinstance(stmt, ast.OutputStmt):
            self._gen_output(stmt)

    def _gen_decl(self, stmt: ast.DeclStmt) -> None:
        for decl in stmt.declarators:
            py_name = self._mangler.mangle(decl.name)
            if decl.init is not None:
                expr_str = self._render(decl.init)
                self._lines.append(f"{self._indent}{py_name} = {expr_str}")
            # else: int x; with no initializer emits nothing

    def _gen_assign(self, stmt: ast.AssignStmt) -> None:
        py_name = self._mangler.mangle(stmt.target.name)
        expr_str = self._render(stmt.value)
        self._lines.append(f"{self._indent}{py_name} = {expr_str}")

    def _gen_input(self, stmt: ast.InputStmt) -> None:
        for target in stmt.targets:
            py_name = self._mangler.mangle(target.name)
            self._lines.append(f"{self._indent}{py_name} = int(next(_tokens))")

    def _gen_output(self, stmt: ast.OutputStmt) -> None:
        items = stmt.items
        if not items:
            return

        # Check if the last item is endl
        has_trailing_endl = isinstance(items[-1], ast.EndlMarker)

        # Build print arguments
        print_args: list[str] = []
        items_to_render = items[:-1] if has_trailing_endl else items

        for item in items_to_render:
            if isinstance(item, ast.EndlMarker):
                # Non-trailing endl becomes "\n"
                print_args.append('"\\n"')
            elif isinstance(item, ast.StringLiteral):
                print_args.append(_python_string_literal(item.value))
            else:
                print_args.append(self._render(item))

        # Handle special case: cout << endl; alone
        if len(items) == 1 and isinstance(items[0], ast.EndlMarker):
            self._lines.append(f"{self._indent}print()")
            return

        kw_parts: list[str] = []
        if len(print_args) > 1:
            kw_parts.append('sep=""')
        if not has_trailing_endl:
            kw_parts.append('end=""')

        all_args = list(print_args) + kw_parts
        args_str = ', '.join(all_args)
        self._lines.append(f"{self._indent}print({args_str})")

    def _render(self, expr: ast.Expr) -> str:
        return render_expr(expr, self._mangler.mangle)


def _python_string_literal(value: str) -> str:
    """Convert an unescaped string to a Python string literal."""
    escaped = value.replace('\\', '\\\\')
    escaped = escaped.replace('"', '\\"')
    escaped = escaped.replace('\n', '\\n')
    escaped = escaped.replace('\t', '\\t')
    return f'"{escaped}"'
