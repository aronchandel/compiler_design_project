"""Python code generator from Intermediate Representation (IR).

Conforms to Phase 3 specification:
- Rebuilds control flow from canonical IR shapes:
  * if / elif / else (with elif folding and pass for empty blocks)
  * while <cond>: (when condition temps inline in evaluation order)
  * while True: fallback with if not (cond): break (when condition temps cannot inline)
  * for loops emitted as init + while
- Compound-assignment peephole (x = x + e -> x += e; div/mod stay x = x // e)
- Functions in definition order with parameters, calls, and returns
- main handling (sys.exit(main()); falling off end returns 0)
"""

from __future__ import annotations

import sys
from typing import TYPE_CHECKING, Any

import cpp2py
from cpp2py.ir.model import (
    IRModule,
    IRFunction,
    Instruction,
    Opcode,
    Const,
    VarRef,
    TempRef,
    StrConst,
    Operand,
    IRType,
)
from cpp2py.codegen.names import NameMangler
from cpp2py.codegen.pyexpr import render_expr
from cpp2py.frontend import ast_nodes as ast
from cpp2py.source import SourceSpan, Pos
from cpp2py.compat.helpers import helper_source, _HELPER_SOURCES
from cpp2py.compat.plan import CompatAction, CompatPlan
from cpp2py.config import CompatMode

if TYPE_CHECKING:
    from cpp2py.diagnostics import DiagnosticSink
    from cpp2py.config import CompilerConfig


def generate(
    module: IRModule,
    sink: DiagnosticSink,
    config: CompilerConfig,
    plan: CompatPlan | None = None,
) -> str:
    """Generate Python source code from an IRModule."""
    gen = IRToPythonGenerator(module, sink, config, plan)
    return gen.generate()


class IRToPythonGenerator:
    """Generates Python source code from an IRModule."""

    def __init__(
        self,
        module: IRModule,
        sink: DiagnosticSink,
        config: CompilerConfig,
        plan: CompatPlan | None = None,
    ) -> None:
        self._module = module
        self._sink = sink
        self._config = config
        self._plan = plan
        self._mangler = NameMangler()
        self._warnings: list[str] = []
        self._indent_unit = "    "
        self._has_input = False
        self._inlined_temps: set[str] = set()
        self._temp_defs: dict[str, Instruction] = {}
        self._current_func: IRFunction | None = None

    def generate(self) -> str:
        # Check if any function reads input
        for func in self._module.functions:
            for instr in func.body:
                if instr.opcode == Opcode.READ:
                    self._has_input = True
                    break

        # Generate each function
        func_blocks: list[str] = []
        for func in self._module.functions:
            func_blocks.append(self._gen_function(func))

        # Collect helpers needed
        helpers_needed: set[str] = set()
        for func in self._module.functions:
            for instr in func.body:
                if instr.opcode == Opcode.CALL and instr.func_name in ("_addr_of", "_get_deref", "_set_deref"):
                    helpers_needed.add("_Ptr")
                if instr.dst and getattr(instr.dst, "type", None) == IRType.PTR:
                    helpers_needed.add("_Ptr")
                for op in instr.operands:
                    if getattr(op, "type", None) == IRType.PTR:
                        helpers_needed.add("_Ptr")

        if self._plan is not None:
            for func in self._module.functions:
                for instr in func.body:
                    dec = self._plan.decisions.get(instr.op_id)
                    if dec and dec.action == CompatAction.HELPER:
                        if dec.helper:
                            helpers_needed.add(dec.helper)
                        if dec.wrap_int_min_div:
                            dst_t = instr.dst.type if instr.dst else IRType.I32
                            helpers_needed.add("_wrap_i64" if dst_t == IRType.I64 else "_wrap_i32")
            if "_cpp_mod" in helpers_needed:
                helpers_needed.add("_cpp_div")

        # Collect warnings from sink
        for diag in self._sink.all():
            if diag.code.startswith("W6"):
                loc = f"{diag.span.start.line}:{diag.span.start.col}" if diag.span is not None else "0:0"
                entry = f"{diag.code} {loc}: {diag.message}" if loc != "0:0" else f"{diag.code}: {diag.message}"
                if entry not in self._warnings:
                    self._warnings.append(entry)

        # Build output lines
        lines: list[str] = []

        # 1. Header notice
        if self._plan is None or self._plan.mode == CompatMode.NAIVE:
            lines.append(
                f"# Generated by cpp2py {cpp2py.__version__} "
                f"(naive integer semantics: no overflow modelling)"
            )
        else:
            lines.append(
                f"# Generated by cpp2py {cpp2py.__version__} "
                f"(mode: {self._plan.mode.value}, overflow: {self._plan.policy.value}, "
                f"helpers: {self._plan.counts.get('helper', 0)}, native: {self._plan.counts.get('native', 0)})"
            )

        # 2. Warning comments
        for w in self._warnings:
            lines.append(f"# WARNING {w}")

        # 3. Imports
        lines.append("import sys")

        # 4. Input prelude if needed
        if self._has_input:
            lines.append("_tokens = iter(sys.stdin.read().split())")

        # 4b. Compatibility helpers
        if helpers_needed:
            lines.append("")
            lines.append("")
            lines.append("# --- compatibility helpers ---")
            for h_name in sorted(helpers_needed):
                lines.append(helper_source(h_name))
                lines.append("")

        # Two blank lines before top-level function definitions (PEP 8)
        lines.append("")
        lines.append("")

        for i, fb in enumerate(func_blocks):
            if i > 0:
                lines.append("")
                lines.append("")
            lines.append(fb)

        # 5. Top-level execution guard
        lines.append("")
        lines.append("")
        lines.append('if __name__ == "__main__":')
        lines.append(f"{self._indent_unit}sys.exit(main())")
        lines.append("")

        text = "\n".join(lines)

        # Self-check with compile()
        try:
            compile(text, "<generated>", "exec")
        except SyntaxError as e:
            self._sink.error("E9001", f"generated invalid Python: {e}")

        return text

    def _gen_function(self, func: IRFunction) -> str:
        self._current_func = func
        self._analyze_temps(func.body)

        body_lines = self._gen_block(func.body, indent_level=1)

        if func.name == "main":
            if not body_lines:
                body_lines.append(f"{self._indent_unit}return 0")
            elif not body_lines[-1].strip().startswith("return"):
                body_lines.append(f"{self._indent_unit}return 0")
        else:
            if not body_lines:
                body_lines.append(f"{self._indent_unit}pass")

        params_str = ", ".join(self._mangler.mangle(p.ir_name) for p in func.params)
        header = f"def {func.name}({params_str}):"
        return header + "\n" + "\n".join(body_lines)

    def _analyze_temps(self, body: list[Instruction]) -> None:
        """Determine which temporaries can be inlined."""
        self._inlined_temps.clear()
        self._temp_defs.clear()

        temp_use_count: dict[str, int] = {}
        temp_def_idx: dict[str, int] = {}
        temp_use_idx: dict[str, int] = {}

        for idx, instr in enumerate(body):
            if instr.dst is not None and isinstance(instr.dst, TempRef):
                t_id = instr.dst.temp_id
                temp_def_idx[t_id] = idx
                self._temp_defs[t_id] = instr

            for op in instr.operands:
                if isinstance(op, TempRef):
                    t_id = op.temp_id
                    temp_use_count[t_id] = temp_use_count.get(t_id, 0) + 1
                    temp_use_idx[t_id] = idx

        single_use_temps = {
            t_id for t_id, count in temp_use_count.items() if count == 1 and t_id in temp_def_idx
        }

        changed = True
        while changed:
            changed = False
            for t_id in list(single_use_temps):
                if t_id in self._inlined_temps:
                    continue

                d_idx = temp_def_idx[t_id]
                u_idx = temp_use_idx[t_id]
                def_instr = self._temp_defs[t_id]

                if def_instr.opcode == Opcode.READ or (
                    def_instr.opcode == Opcode.CALL and def_instr.func_name in ("_set_index", "_set_deref", "_array_init")
                ):
                    continue

                can_inline = True
                for k in range(d_idx + 1, u_idx):
                    between_instr = body[k]
                    if between_instr.dst is None or not isinstance(between_instr.dst, TempRef):
                        can_inline = False
                        break
                    between_temp_id = between_instr.dst.temp_id
                    if between_temp_id not in self._inlined_temps and between_temp_id != t_id:
                        can_inline = False
                        break
                    if between_instr.opcode == Opcode.CALL and def_instr.opcode == Opcode.CALL:
                        # Do not inline across another user function call
                        can_inline = False
                        break

                if can_inline:
                    self._inlined_temps.add(t_id)
                    changed = True

    def _gen_block(self, instrs: list[Instruction], indent_level: int) -> list[str]:
        """Rebuild structured code from a list of instructions."""
        lines: list[str] = []
        indent = self._indent_unit * indent_level
        i = 0
        n = len(instrs)

        # Pre-scan for qualifying idiomatic for loops
        idiomatic_matches: dict[int, tuple[str, str, list[Instruction], int]] = {}
        suppressed_inits: set[int] = set()

        if getattr(self._config, "idiomatic_loops", False):
            for k in range(n):
                ins = instrs[k]
                if ins.opcode == Opcode.LABEL and (ins.label_name or "").startswith("loop_head_"):
                    rid = (ins.label_name or "")[len("loop_head_"):]
                    l_body = f"loop_body_{rid}"
                    l_end = f"loop_end_{rid}"
                    l_head = f"loop_head_{rid}"

                    # Find branch
                    b_idx = -1
                    for j in range(k + 1, n):
                        if instrs[j].opcode == Opcode.BRANCH:
                            t_target = str(instrs[j].operands[1]) if len(instrs[j].operands) > 1 else ""
                            if t_target == l_body:
                                b_idx = j
                                break
                    if b_idx != -1:
                        b_start = b_idx + 1
                        if b_start < n and instrs[b_start].opcode == Opcode.LABEL and instrs[b_start].label_name == l_body:
                            b_start += 1
                        j_idx = -1
                        e_idx = -1
                        for j in range(b_start, n):
                            if instrs[j].opcode == Opcode.JUMP and instrs[j].label_name == l_head:
                                j_idx = j
                            elif instrs[j].opcode == Opcode.LABEL and instrs[j].label_name == l_end:
                                e_idx = j
                                break
                        if j_idx != -1 and e_idx != -1:
                            m = self._try_match_idiomatic_loop(instrs, k, b_idx, b_start, j_idx, rid)
                            if m is not None:
                                v_str, r_str, r_body, init_idx = m
                                idiomatic_matches[k] = (v_str, r_str, r_body, e_idx)
                                suppressed_inits.add(init_idx)

        while i < n:
            if i in suppressed_inits:
                i += 1
                continue

            if i in idiomatic_matches:
                v_str, r_str, r_body, e_idx = idiomatic_matches[i]
                lines.append(f"{indent}for {v_str} in {r_str}:")
                inner_lines = self._gen_block(r_body, indent_level + 1)
                if not inner_lines:
                    lines.append(f"{indent}{self._indent_unit}pass")
                else:
                    lines.extend(inner_lines)
                i = e_idx + 1
                continue

            instr = instrs[i]

            # 1. Loop Region: starts with loop_head_rN
            if instr.opcode == Opcode.LABEL and (instr.label_name or "").startswith("loop_head_"):
                rid = (instr.label_name or "")[len("loop_head_"):]
                l_body = f"loop_body_{rid}"
                l_end = f"loop_end_{rid}"

                # Find branch
                branch_idx = -1
                for j in range(i + 1, n):
                    if instrs[j].opcode == Opcode.BRANCH:
                        t_target = str(instrs[j].operands[1]) if len(instrs[j].operands) > 1 else ""
                        if t_target == l_body:
                            branch_idx = j
                            break

                if branch_idx != -1:
                    cond_instrs = instrs[i + 1:branch_idx]
                    branch_instr = instrs[branch_idx]
                    cond_op = branch_instr.operands[0]

                    # Find body instructions and loop end
                    body_start_idx = branch_idx + 1
                    # Skip loop_body_rid: label
                    if body_start_idx < n and instrs[body_start_idx].opcode == Opcode.LABEL and instrs[body_start_idx].label_name == l_body:
                        body_start_idx += 1

                    # Find jump loop_head_rid and loop_end_rid:
                    jump_idx = -1
                    end_idx = -1
                    l_head = f"loop_head_{rid}"
                    for j in range(body_start_idx, n):
                        if instrs[j].opcode == Opcode.JUMP and instrs[j].label_name == l_head:
                            jump_idx = j
                        elif instrs[j].opcode == Opcode.LABEL and instrs[j].label_name == l_end:
                            end_idx = j
                            break

                    if jump_idx != -1 and end_idx != -1:
                        body_instrs = instrs[body_start_idx:jump_idx]

                        # Check if condition temps can inline directly
                        can_inline_cond = self._can_inline_loop_cond(cond_instrs, cond_op)

                        if can_inline_cond:
                            cond_str = self._render_operand_expr(cond_op)
                            lines.append(f"{indent}while {cond_str}:")
                            inner_lines = self._gen_block(body_instrs, indent_level + 1)
                            if not inner_lines:
                                lines.append(f"{indent}{self._indent_unit}pass")
                            else:
                                lines.extend(inner_lines)
                        else:
                            # Fallback: while True: + explicit condition + if not (cond): break
                            lines.append(f"{indent}while True:")
                            cond_lines: list[str] = []
                            for ci in cond_instrs:
                                self._gen_instruction(ci, cond_lines, indent_level + 1)
                            cond_str = self._render_operand_expr(cond_op)
                            cond_lines.append(f"{indent}{self._indent_unit}if not ({cond_str}):")
                            cond_lines.append(f"{indent}{self._indent_unit}{self._indent_unit}break")
                            inner_lines = self._gen_block(body_instrs, indent_level + 1)
                            lines.extend(cond_lines)
                            lines.extend(inner_lines)

                        i = end_idx + 1
                        continue

            # 2. If Region: starts with branch c, if_then_rN, if_else_rN
            if instr.opcode == Opcode.BRANCH:
                t_target = str(instr.operands[1]) if len(instr.operands) > 1 else ""
                if t_target.startswith("if_then_"):
                    rid = t_target[len("if_then_"):]
                    l_then = f"if_then_{rid}"
                    l_else = f"if_else_{rid}"
                    l_end = f"if_end_{rid}"

                    cond_op = instr.operands[0]

                    # Find then_start, else_start, end_idx
                    then_start = -1
                    else_start = -1
                    jump_end_idx = -1
                    end_idx = -1

                    for j in range(i + 1, n):
                        cur = instrs[j]
                        if cur.opcode == Opcode.LABEL:
                            name = cur.label_name or ""
                            if name == l_then:
                                then_start = j + 1
                            elif name == l_else:
                                else_start = j + 1
                            elif name == l_end:
                                end_idx = j
                                break
                        elif cur.opcode == Opcode.JUMP and cur.label_name == l_end:
                            if jump_end_idx == -1:
                                jump_end_idx = j

                    if then_start != -1 and else_start != -1 and jump_end_idx != -1 and end_idx != -1:
                        then_instrs = instrs[then_start:jump_end_idx]
                        else_instrs = instrs[else_start:end_idx]

                        cond_str = self._render_operand_expr(cond_op)
                        lines.append(f"{indent}if {cond_str}:")
                        then_lines = self._gen_block(then_instrs, indent_level + 1)
                        if not then_lines:
                            lines.append(f"{indent}{self._indent_unit}pass")
                        else:
                            lines.extend(then_lines)

                        # Handle else / elif
                        self._emit_else_or_elif(else_instrs, indent_level, lines)

                        i = end_idx + 1
                        continue

            # 3. Normal instruction
            self._gen_instruction(instr, lines, indent_level)
            i += 1

        return lines

    def _can_inline_loop_cond(self, cond_instrs: list[Instruction], cond_op: Operand) -> bool:
        """Check if loop condition temps can be inlined into a single expression."""
        if not cond_instrs:
            return True

        # If any instruction in cond_instrs is a user CALL, do NOT inline
        for instr in cond_instrs:
            if instr.opcode == Opcode.CALL and not (instr.func_name or "").startswith("_"):
                return False

        # All temps defined in cond_instrs (except the final cond_op) must be inlined
        if isinstance(cond_op, TempRef):
            for instr in cond_instrs:
                if instr.dst is not None and isinstance(instr.dst, TempRef):
                    t_id = instr.dst.temp_id
                    if t_id != cond_op.temp_id and t_id not in self._inlined_temps:
                        return False
            # Check if cond_op itself can be rendered
            return True

        return True

    def _try_match_idiomatic_loop(
        self,
        instrs: list[Instruction],
        loop_head_idx: int,
        branch_idx: int,
        body_start_idx: int,
        jump_idx: int,
        rid: str,
    ) -> tuple[str, str, list[Instruction], int] | None:
        """Attempt to match a for loop qualifying for Python for i in range(...) syntax.

        Returns (var_str, range_str, real_body_instrs, init_idx) or None.
        """
        if not getattr(self._config, "idiomatic_loops", False):
            return None

        if self._current_func is None:
            return None

        region = self._current_func.regions.get(rid)
        if region is None or region.kind != "for":
            return None

        # 1. loop_var must be declared in the for init
        if not getattr(region, "loop_var_declared_in_init", False) or region.loop_var is None:
            return None

        loop_var_sym = region.loop_var

        # Find initialization right before loop_head
        init_idx = -1
        for k in range(loop_head_idx - 1, -1, -1):
            ins = instrs[k]
            if ins.dst and isinstance(ins.dst, VarRef) and ins.dst.symbol_id == loop_var_sym:
                if ins.opcode == Opcode.ASSIGN:
                    init_idx = k
                break
            if ins.opcode == Opcode.DECLARE:
                continue
            if ins.dst and isinstance(ins.dst, TempRef) and ins.dst.temp_id in self._inlined_temps:
                continue
            break

        if init_idx == -1:
            return None

        init_instr = instrs[init_idx]
        a_op = init_instr.operands[0]
        loop_var_ref = init_instr.dst

        # 2. Check update at the end of body_instrs
        if jump_idx - body_start_idx < 2:
            return None

        assign_step = instrs[jump_idx - 1]
        def_step = instrs[jump_idx - 2]

        if assign_step.opcode != Opcode.ASSIGN or not (
            assign_step.dst and isinstance(assign_step.dst, VarRef) and assign_step.dst.symbol_id == loop_var_sym
        ):
            return None

        if def_step.dst != assign_step.operands[0]:
            return None

        if def_step.opcode not in (Opcode.ADD, Opcode.SUB):
            return None

        if not (isinstance(def_step.operands[0], VarRef) and def_step.operands[0].symbol_id == loop_var_sym):
            return None

        if not isinstance(def_step.operands[1], Const):
            return None

        step_c = def_step.operands[1].value
        if step_c <= 0:
            return None

        is_increasing = (def_step.opcode == Opcode.ADD)
        is_decreasing = (def_step.opcode == Opcode.SUB)

        real_body_instrs = instrs[body_start_idx : jump_idx - 2]

        # 3. loop_var must not be written in real_body_instrs
        for ins in real_body_instrs:
            if ins.dst and isinstance(ins.dst, VarRef) and ins.dst.symbol_id == loop_var_sym:
                return None
            if ins.opcode == Opcode.READ:
                for rop in ins.operands:
                    if isinstance(rop, VarRef) and rop.symbol_id == loop_var_sym:
                        return None

        # 4. Check condition and bound operand
        cond_instrs = instrs[loop_head_idx + 1 : branch_idx]
        branch_instr = instrs[branch_idx]
        cond_op = branch_instr.operands[0]

        cmp_instr = next((ci for ci in cond_instrs if ci.dst == cond_op), None)
        if cmp_instr is None or cmp_instr.opcode != Opcode.CMP:
            return None

        cmp_op = cmp_instr.cmp_op
        op1 = cmp_instr.operands[0]
        op2 = cmp_instr.operands[1]

        if not (isinstance(op1, VarRef) and op1.symbol_id == loop_var_sym):
            return None

        bound_op = op2
        if isinstance(bound_op, Const):
            pass
        elif isinstance(bound_op, VarRef):
            bound_sym = bound_op.symbol_id
            for ins in real_body_instrs:
                if ins.dst and isinstance(ins.dst, VarRef) and ins.dst.symbol_id == bound_sym:
                    return None
                if ins.opcode == Opcode.READ:
                    for rop in ins.operands:
                        if isinstance(rop, VarRef) and rop.symbol_id == bound_sym:
                            return None
        else:
            return None

        # 5. Check condition direction
        if is_increasing:
            if cmp_op not in ("lt", "le"):
                return None
        elif is_decreasing:
            if cmp_op not in ("gt", "ge"):
                return None
        else:
            return None

        # Map to range(...)
        var_str = self._mangler.mangle(loop_var_ref.ir_name)
        a_str = self._render_operand_expr(a_op)

        if cmp_op == "lt":
            b_str = self._render_operand_expr(bound_op)
            r_str = f"range({a_str}, {b_str})" if step_c == 1 else f"range({a_str}, {b_str}, {step_c})"
        elif cmp_op == "le":
            if isinstance(bound_op, Const):
                b_str = str(bound_op.value + 1)
            else:
                b_str = f"{self._render_operand_expr(bound_op)} + 1"
            r_str = f"range({a_str}, {b_str})" if step_c == 1 else f"range({a_str}, {b_str}, {step_c})"
        elif cmp_op == "gt":
            b_str = self._render_operand_expr(bound_op)
            r_str = f"range({a_str}, {b_str}, -{step_c})"
        elif cmp_op == "ge":
            if isinstance(bound_op, Const):
                b_str = str(bound_op.value - 1)
            else:
                b_str = f"{self._render_operand_expr(bound_op)} - 1"
            r_str = f"range({a_str}, {b_str}, -{step_c})"
        else:
            return None

        return var_str, r_str, real_body_instrs, init_idx

    def _emit_else_or_elif(self, else_instrs: list[Instruction], indent_level: int, lines: list[str]) -> None:
        """Emit else or elif clause, folding elif chains when possible."""
        indent = self._indent_unit * indent_level

        # Check if else_instrs has actual executable instructions
        real_instrs = [
            ins for ins in else_instrs
            if ins.opcode not in (Opcode.LABEL, Opcode.DECLARE)
        ]
        if not real_instrs:
            return

        # Check if else_instrs is exactly one if-region (elif folding)
        branch_instr = None
        for ins in real_instrs:
            if ins.opcode == Opcode.BRANCH and str(ins.operands[1]).startswith("if_then_"):
                branch_instr = ins
                break

        if branch_instr is not None:
            # Check if all instructions in else_instrs belong to this if-region
            t_target = str(branch_instr.operands[1])
            rid = t_target[len("if_then_"):]
            l_end = f"if_end_{rid}"
            if else_instrs[-1].opcode == Opcode.LABEL and else_instrs[-1].label_name == l_end:
                # Check condition temps can be inlined into elif
                b_idx = else_instrs.index(branch_instr)
                cond_temps = else_instrs[:b_idx]
                if all(ins.dst is not None and isinstance(ins.dst, TempRef) and ins.dst.temp_id in self._inlined_temps for ins in cond_temps):
                    # Fold into elif!
                    cond_str = self._render_operand_expr(branch_instr.operands[0])
                    lines.append(f"{indent}elif {cond_str}:")

                    l_then = f"if_then_{rid}"
                    l_else = f"if_else_{rid}"
                    then_start = else_instrs.index(next(ins for ins in else_instrs if ins.label_name == l_then)) + 1
                    jump_end = else_instrs.index(next(ins for ins in else_instrs if ins.opcode == Opcode.JUMP and ins.label_name == l_end))
                    else_start = else_instrs.index(next(ins for ins in else_instrs if ins.label_name == l_else)) + 1
                    end_idx = len(else_instrs) - 1

                    then_sub = else_instrs[then_start:jump_end]
                    else_sub = else_instrs[else_start:end_idx]

                    then_lines = self._gen_block(then_sub, indent_level + 1)
                    if not then_lines:
                        lines.append(f"{indent}{self._indent_unit}pass")
                    else:
                        lines.extend(then_lines)

                    self._emit_else_or_elif(else_sub, indent_level, lines)
                    return

        # Regular else
        lines.append(f"{indent}else:")
        else_lines = self._gen_block(else_instrs, indent_level + 1)
        if not else_lines:
            lines.append(f"{indent}{self._indent_unit}pass")
        else:
            lines.extend(else_lines)

    def _gen_instruction(self, instr: Instruction, lines: list[str], indent_level: int = 1) -> None:
        opcode = instr.opcode
        indent = self._indent_unit * indent_level

        # Check for div / mod warnings in naive mode ONLY
        if self._plan is None or self._plan.mode == CompatMode.NAIVE:
            if opcode in (Opcode.DIV, Opcode.MOD):
                op_sym = "/" if opcode == Opcode.DIV else "%"
                msg = f"'{op_sym}' is emitted as Python floor division; the result differs from C++ when an operand is negative"
                self._sink.warning("W6001", msg, span=instr.span)

                loc = f"{instr.span.start.line}:{instr.span.start.col}" if instr.span is not None else "0:0"
                warning_entry = f"W6001 {loc}: {msg}"
                if warning_entry not in self._warnings:
                    self._warnings.append(warning_entry)

        # Skip inlined temps
        if instr.dst is not None and isinstance(instr.dst, TempRef) and instr.dst.temp_id in self._inlined_temps:
            return

        if opcode in (Opcode.DECLARE, Opcode.LABEL, Opcode.JUMP):
            return

        elif opcode == Opcode.ASSIGN:
            dst_name = self._mangle_target(instr.dst)

            # Peephole for compound assignment: x += e, x -= e, x *= e
            src_op = instr.operands[0]
            if isinstance(src_op, TempRef) and src_op.temp_id in self._temp_defs:
                def_instr = self._temp_defs[src_op.temp_id]
                def_decision = self._plan.decisions.get(def_instr.op_id) if self._plan else None
                if def_decision is None or def_decision.action == CompatAction.NATIVE:
                    if def_instr.opcode in (Opcode.ADD, Opcode.SUB, Opcode.MUL):
                        left_op = def_instr.operands[0]
                        if isinstance(left_op, VarRef) and isinstance(instr.dst, VarRef) and left_op.ir_name == instr.dst.ir_name:
                            op_symbol = {Opcode.ADD: "+=", Opcode.SUB: "-=", Opcode.MUL: "*="}[def_instr.opcode]
                            rhs_str = self._render_operand_expr(def_instr.operands[1])
                            lines.append(f"{indent}{dst_name} {op_symbol} {rhs_str}")
                            return

            val_expr = self._render_operand_expr(src_op)
            lines.append(f"{indent}{dst_name} = {val_expr}")

        elif opcode in (Opcode.ADD, Opcode.SUB, Opcode.MUL, Opcode.DIV, Opcode.MOD, Opcode.NEG, Opcode.CMP, Opcode.CAST):
            dst_name = self._mangle_target(instr.dst)
            ast_expr = self._build_ast_for_instr(instr)
            val_str = render_expr(ast_expr, self._mangle_name)
            lines.append(f"{indent}{dst_name} = {val_str}")

        elif opcode == Opcode.CALL:
            callee = instr.func_name or ""
            if callee == "_array_init":
                dst_name = self._mangle_target(instr.dst)
                elem_strs = [self._render_operand_expr(op) for op in instr.operands]
                lines.append(f"{indent}{dst_name} = [{', '.join(elem_strs)}]")
            elif callee == "_get_index":
                dst_name = self._mangle_target(instr.dst)
                arr_str = self._render_operand_expr(instr.operands[0])
                idx_str = self._render_operand_expr(instr.operands[1])
                lines.append(f"{indent}{dst_name} = {arr_str}[{idx_str}]")
            elif callee == "_set_index":
                arr_str = self._render_operand_expr(instr.operands[0])
                idx_str = self._render_operand_expr(instr.operands[1])
                val_str = self._render_operand_expr(instr.operands[2])
                lines.append(f"{indent}{arr_str}[{idx_str}] = {val_str}")
            elif callee == "_addr_of":
                dst_name = self._mangle_target(instr.dst)
                target_str = self._render_operand_expr(instr.operands[0])
                offset_str = self._render_operand_expr(instr.operands[1]) if len(instr.operands) > 1 else "0"
                lines.append(f"{indent}{dst_name} = _Ptr({target_str}, {offset_str})")
            elif callee == "_get_deref":
                dst_name = self._mangle_target(instr.dst)
                ptr_str = self._render_operand_expr(instr.operands[0])
                lines.append(f"{indent}{dst_name} = {ptr_str}[0]")
            elif callee == "_set_deref":
                ptr_str = self._render_operand_expr(instr.operands[0])
                val_str = self._render_operand_expr(instr.operands[1])
                lines.append(f"{indent}{ptr_str}[0] = {val_str}")
            else:
                m_callee = self._mangler.mangle(callee)
                args_str = ", ".join(self._render_operand_expr(op) for op in instr.operands)
                if instr.dst is not None:
                    dst_name = self._mangle_target(instr.dst)
                    lines.append(f"{indent}{dst_name} = {m_callee}({args_str})")
                else:
                    lines.append(f"{indent}{m_callee}({args_str})")

        elif opcode == Opcode.READ:
            target_name = self._mangle_target(instr.dst or instr.operands[0])
            lines.append(f"{indent}{target_name} = int(next(_tokens))")

        elif opcode == Opcode.PRINT:
            items = instr.operands
            has_trailing_endl = instr.newline

            print_args: list[str] = []
            for item in items:
                if isinstance(item, StrConst):
                    print_args.append(_python_string_literal(item.text))
                else:
                    print_args.append(self._render_operand_expr(item))

            if not print_args and has_trailing_endl:
                lines.append(f"{indent}print()")
                return

            kw_parts: list[str] = []
            if len(print_args) > 1:
                kw_parts.append('sep=""')
            if not has_trailing_endl:
                kw_parts.append('end=""')

            all_args = list(print_args) + kw_parts
            args_str = ", ".join(all_args)
            lines.append(f"{indent}print({args_str})")

        elif opcode == Opcode.RETURN:
            if instr.operands:
                val_str = self._render_operand_expr(instr.operands[0])
                lines.append(f"{indent}return {val_str}")
            else:
                lines.append(f"{indent}return")

    def _mangle_target(self, target: Any) -> str:
        if isinstance(target, VarRef):
            return self._mangler.mangle(target.ir_name)
        elif isinstance(target, TempRef):
            return self._mangler.mangle(target.temp_id)
        return self._mangler.mangle(str(target))

    def _mangle_name(self, name: str) -> str:
        if name in _HELPER_SOURCES:
            return name
        return self._mangler.mangle(name)

    def _render_operand_expr(self, operand: Operand) -> str:
        ast_expr = self._build_ast_expr(operand)
        return render_expr(ast_expr, self._mangle_name)

    def _build_ast_expr(self, operand: Operand) -> ast.Expr:
        dummy_span = SourceSpan(file="", start=Pos(1, 1, 0), end=Pos(1, 1, 0))

        if isinstance(operand, Const):
            if operand.type == IRType.PTR and operand.value == 0:
                return ast.CallExpr("_Ptr", (ast.NullptrLiteral(dummy_span), ast.IntLiteral(0, dummy_span)), dummy_span)
            return ast.IntLiteral(operand.value, dummy_span)

        elif isinstance(operand, VarRef):
            return ast.NameExpr(operand.ir_name, dummy_span)

        elif isinstance(operand, TempRef):
            if operand.temp_id in self._inlined_temps and operand.temp_id in self._temp_defs:
                def_instr = self._temp_defs[operand.temp_id]
                return self._build_ast_for_instr(def_instr)
            return ast.NameExpr(operand.temp_id, dummy_span)

        elif isinstance(operand, StrConst):
            return ast.StringLiteral(operand.text, f'"{operand.text}"', dummy_span)

        return ast.NameExpr(str(operand), dummy_span)

    def _build_ast_for_instr(self, instr: Instruction) -> ast.Expr:
        dummy_span = instr.span or SourceSpan(file="", start=Pos(1, 1, 0), end=Pos(1, 1, 0))
        opcode = instr.opcode

        decision = self._plan.decisions.get(instr.op_id) if self._plan else None
        if decision is not None and decision.action == CompatAction.HELPER:
            helper_name = decision.helper or ""
            if opcode == Opcode.DIV:
                left = self._build_ast_expr(instr.operands[0])
                right = self._build_ast_expr(instr.operands[1])
                call_expr = ast.CallExpr(helper_name, (left, right), dummy_span)
                if decision.wrap_int_min_div:
                    wrap_fn = "_wrap_i64" if (instr.dst and instr.dst.type == IRType.I64) else "_wrap_i32"
                    return ast.CallExpr(wrap_fn, (call_expr,), dummy_span)
                return call_expr
            elif opcode == Opcode.MOD:
                left = self._build_ast_expr(instr.operands[0])
                right = self._build_ast_expr(instr.operands[1])
                call_expr = ast.CallExpr(helper_name, (left, right), dummy_span)
                if decision.wrap_int_min_div:
                    wrap_fn = "_wrap_i64" if (instr.dst and instr.dst.type == IRType.I64) else "_wrap_i32"
                    return ast.CallExpr(wrap_fn, (call_expr,), dummy_span)
                return call_expr
            elif opcode in (Opcode.ADD, Opcode.SUB, Opcode.MUL):
                op_map = {
                    Opcode.ADD: "+",
                    Opcode.SUB: "-",
                    Opcode.MUL: "*",
                }
                left = self._build_ast_expr(instr.operands[0])
                right = self._build_ast_expr(instr.operands[1])
                bin_expr = ast.BinaryExpr(op_map[opcode], left, right, dummy_span)
                return ast.CallExpr(helper_name, (bin_expr,), dummy_span)
            elif opcode == Opcode.NEG:
                operand = self._build_ast_expr(instr.operands[0])
                un_expr = ast.UnaryExpr("-", operand, dummy_span)
                return ast.CallExpr(helper_name, (un_expr,), dummy_span)
            elif opcode == Opcode.CAST:
                src = self._build_ast_expr(instr.operands[0])
                if helper_name:
                    return ast.CallExpr(helper_name, (src,), dummy_span)
                return src

        if opcode == Opcode.CAST:
            return self._build_ast_expr(instr.operands[0])

        if opcode in (Opcode.ADD, Opcode.SUB, Opcode.MUL, Opcode.DIV, Opcode.MOD):
            op_map = {
                Opcode.ADD: "+",
                Opcode.SUB: "-",
                Opcode.MUL: "*",
                Opcode.DIV: "/",
                Opcode.MOD: "%",
            }
            left = self._build_ast_expr(instr.operands[0])
            right = self._build_ast_expr(instr.operands[1])
            return ast.BinaryExpr(op_map[opcode], left, right, dummy_span)

        elif opcode == Opcode.NEG:
            operand = self._build_ast_expr(instr.operands[0])
            return ast.UnaryExpr("-", operand, dummy_span)

        elif opcode == Opcode.CMP:
            cmp_map = {
                'lt': '<', 'le': '<=', 'gt': '>', 'ge': '>=', 'eq': '==', 'ne': '!='
            }
            op_sym = cmp_map.get(instr.cmp_op or "", "==")
            left = self._build_ast_expr(instr.operands[0])
            right = self._build_ast_expr(instr.operands[1])
            return ast.BinaryExpr(op_sym, left, right, dummy_span)

        elif opcode == Opcode.CALL:
            callee = instr.func_name or ""
            if callee == "_get_index":
                arr = self._build_ast_expr(instr.operands[0])
                idx = self._build_ast_expr(instr.operands[1])
                return ast.IndexExpr(arr, idx, dummy_span)
            elif callee == "_get_deref":
                ptr = self._build_ast_expr(instr.operands[0])
                return ast.IndexExpr(ptr, ast.IntLiteral(0, dummy_span), dummy_span)
            elif callee == "_addr_of":
                target = self._build_ast_expr(instr.operands[0])
                offset = self._build_ast_expr(instr.operands[1]) if len(instr.operands) > 1 else ast.IntLiteral(0, dummy_span)
                return ast.CallExpr("_Ptr", (target, offset), dummy_span)
            args = tuple(self._build_ast_expr(op) for op in instr.operands)
            return ast.CallExpr(callee, args, dummy_span)

        elif opcode == Opcode.ASSIGN:
            return self._build_ast_expr(instr.operands[0])

        raise NotImplementedError(f"Cannot build AST expr for opcode: {opcode}")


def _python_string_literal(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return f'"{escaped}"'
