def test_ac5_10_plan_fidelity_data(repo_root):
    cpp_file = repo_root / "examples" / "phase5" / "assumed_range_demo.cpp"
    source = cpp_file.read_text(encoding="utf-8")
    res = compile_source(source, str(cpp_file), CompilerConfig(assumed_ranges={"main.x": Interval(0, 1000)}))
    assert res.plan is not None
    assert len(res.plan.assumptions) >= 1
    assert any(d.reason != "" for d in res.plan.decisions.values())
    assert any(len(d.operand_ranges) > 0 for d in res.plan.decisions.values())
