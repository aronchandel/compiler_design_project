def _run_py(code: str, stdin_text: str = "") -> str:
    res = subprocess.run(
        [sys.executable, "-c", code],
        input=stdin_text,
        capture_output=True,
        text=True,
        check=True,
    )
    return res.stdout.replace("\r\n", "\n")

def test_ac5_4_helper_counts(repo_root):

    p_no_helper = repo_root / "examples" / "phase5" / "div_no_helper_needed.cpp"
    code_no_helper = p_no_helper.read_text(encoding="utf-8")
    res_rg = compile_source(code_no_helper, str(p_no_helper), CompilerConfig(compat_mode=CompatMode.RANGE_GUIDED))
    assert res_rg.success
    assert "_cpp_" not in res_rg.python_source

    p_needs_helper = repo_root / "examples" / "phase5" / "div_needs_helper.cpp"
    code_needs_helper = p_needs_helper.read_text(encoding="utf-8")
    res_rg2 = compile_source(code_needs_helper, str(p_needs_helper), CompilerConfig(compat_mode=CompatMode.RANGE_GUIDED))
    assert res_rg2.success
    assert "_cpp_div" in res_rg2.python_source or "_cpp_mod" in res_rg2.python_source

    res_always1 = compile_source(code_no_helper, str(p_no_helper), CompilerConfig(compat_mode=CompatMode.ALWAYS))
    assert res_always1.success
    assert "_cpp_div" in res_always1.python_source
    assert "_cpp_mod" in res_always1.python_source

    res_always2 = compile_source(code_needs_helper, str(p_needs_helper), CompilerConfig(compat_mode=CompatMode.ALWAYS))
    assert res_always2.success
    assert "_cpp_div" in res_always2.python_source
    assert "_cpp_mod" in res_always2.python_source

def test_ac5_5_self_consistency_on_examples(repo_root):
    examples_dir = repo_root / "examples" / "phase5"

    for ex in PHASE5_EXAMPLES:
        cpp_file = examples_dir / f"{ex}.cpp"
        expected_file = examples_dir / f"{ex}.expected"
        in_file = examples_dir / f"{ex}.in"

        assert cpp_file.exists(), f"Missing {cpp_file}"
        assert expected_file.exists(), f"Missing {expected_file}"

        source_text = cpp_file.read_text(encoding="utf-8")
        expected_stdout = expected_file.read_text(encoding="utf-8").replace("\r\n", "\n")
        stdin_text = in_file.read_text(encoding="utf-8") if in_file.exists() else ""

        overflow = OverflowPolicy.WRAP if ex in ("boundary_int_min", "narrowing") else OverflowPolicy.ASSUME_NO_OVERFLOW
        assumed = {"main.x": Interval(0, 1000)} if ex == "assumed_range_demo" else {}

        cfg_rg = CompilerConfig(
            target=TargetModel(overflow_policy=overflow),
            compat_mode=CompatMode.RANGE_GUIDED,
            assumed_ranges=assumed,
        )
        res_rg = compile_source(source_text, str(cpp_file), cfg_rg)
        assert res_rg.success, f"Failed range_guided compile for {ex}"
        out_rg = _run_py(res_rg.python_source, stdin_text)
        assert out_rg == expected_stdout, f"Mismatched range_guided output for {ex}: expected {expected_stdout!r}, got {out_rg!r}"

        cfg_always = CompilerConfig(
            target=TargetModel(overflow_policy=overflow),
            compat_mode=CompatMode.ALWAYS,
            assumed_ranges=assumed,
        )
        res_always = compile_source(source_text, str(cpp_file), cfg_always)
        assert res_always.success, f"Failed always compile for {ex}"
        out_always = _run_py(res_always.python_source, stdin_text)
        assert out_always == expected_stdout, f"Mismatched always output for {ex}: expected {expected_stdout!r}, got {out_always!r}"

        assert out_rg == out_always

def test_ac5_6_naive_mode_reproduces_phase4(repo_root):
    fold_cpp = repo_root / "examples" / "phase4" / "fold_demo.cpp"
    source = fold_cpp.read_text(encoding="utf-8")
    res = compile_source(source, str(fold_cpp), CompilerConfig(compat_mode=CompatMode.NAIVE))
    assert res.success

    lines = res.python_source.splitlines()
    assert lines[0] == "# Generated by cpp2py 0.0.0 (naive integer semantics: no overflow modelling)"
    out = _run_py(res.python_source)
    assert out.strip() == "48"

def test_ac5_7_artifacts_determinism(repo_root, tmp_path):
    cpp_file = repo_root / "examples" / "phase5" / "assumed_range_demo.cpp"
    source = cpp_file.read_text(encoding="utf-8")

    plan1 = tmp_path / "plan1.json"
    ranges1 = tmp_path / "ranges1.json"
    cfg1 = CompilerConfig(
        assumed_ranges={"main.x": Interval(0, 1000)},
        ranges_out=str(ranges1),
        compat_plan_out=str(plan1),
    )
    compile_source(source, str(cpp_file), cfg1)

    plan2 = tmp_path / "plan2.json"
    ranges2 = tmp_path / "ranges2.json"
    cfg2 = CompilerConfig(
        assumed_ranges={"main.x": Interval(0, 1000)},
        ranges_out=str(ranges2),
        compat_plan_out=str(plan2),
    )
    compile_source(source, str(cpp_file), cfg2)

    assert plan1.read_bytes() == plan2.read_bytes()
    assert ranges1.read_bytes() == ranges2.read_bytes()

