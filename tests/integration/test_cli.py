import subprocess
import sys
from pathlib import Path
import pytest


ERROR_EXPECTATIONS = {
    "bad_char": "E1001",
    "compound_assign": "E4001",
    "literal_too_big": "E1004",
    "missing_semicolon": "E2002",
    "nested_block": "E4001",
    "no_main": "E2001",
    "redeclared": "E3002",
    "return_value": "E4001",
    "undeclared_var": "E3001",
    "unsupported_directive": "E1005",
    "unsupported_float": "E4002",
    "unsupported_header": "E4003",
    "unsupported_while": "E4001",
    "unterminated_string": "E1002",
    "use_before_init": "E3003",
}


def test_cli_version(run_cli):
    res = run_cli("--version")
    assert res.returncode == 0
    assert "cpp2py 0.0.0" in res.stdout


def test_cli_dump_ast(run_cli, repo_root):
    src = repo_root / "examples" / "phase1" / "arith_basic.cpp"
    res = run_cli("translate", "--dump-ast", str(src))
    assert res.returncode == 0
    assert "Program" in res.stdout
    assert "FunctionDef main -> int" in res.stdout
    assert "import sys" not in res.stdout


def test_cli_translate_success(run_cli, repo_root, tmp_path):
    src = repo_root / "examples" / "phase1" / "arith_basic.cpp"
    out_file = tmp_path / "arith.py"
    res = run_cli("translate", str(src), "-o", str(out_file))
    assert res.returncode == 0
    assert out_file.exists()
    content = out_file.read_text(encoding="utf-8")
    assert "# Generated by cpp2py" in content


def test_cli_neg_division_warning(run_cli, repo_root, tmp_path):
    src = repo_root / "examples" / "phase1" / "neg_division_warning.cpp"
    out_file = tmp_path / "neg.py"
    res = run_cli("translate", str(src), "-o", str(out_file))
    assert res.returncode == 0
    assert "W6001" in res.stderr
    assert out_file.exists()
    content = out_file.read_text(encoding="utf-8")
    assert "# WARNING W6001" in content


@pytest.mark.parametrize("name,expected_code", sorted(ERROR_EXPECTATIONS.items()))
def test_cli_error_cases(run_cli, repo_root, tmp_path, name, expected_code):
    err_file = repo_root / "examples" / "phase1" / "errors" / f"{name}.cpp"
    assert err_file.exists(), f"Missing error file {err_file}"

    out_file = tmp_path / f"{name}_out.py"
    res = run_cli("translate", str(err_file), "-o", str(out_file))

    # Exit code must be 2
    assert res.returncode == 2, f"Expected returncode 2, got {res.returncode}. stderr: {res.stderr}"

    # Stderr must contain the diagnostic code
    assert expected_code in res.stderr, f"Expected {expected_code} in stderr, got: {res.stderr}"

    # -o file must not exist
    assert not out_file.exists(), f"Output file {out_file} was created despite errors!"
