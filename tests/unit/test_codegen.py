import pytest
from cpp2py.compiler import compile_source
from cpp2py.config import CompilerConfig


def compile_cxx(text: str):
    res = compile_source(text, "test.cpp", CompilerConfig())
    return res


def test_codegen_header_notice():
    res = compile_cxx("int main() { return 0; }")
    assert res.success
    assert "# Generated by cpp2py 0.0.0 (naive integer semantics: no overflow modelling)" in res.python_source


def test_codegen_structure_and_pep8():
    res = compile_cxx("int main() { return 0; }")
    assert res.success
    lines = res.python_source.splitlines()
    assert "import sys" in res.python_source
    assert "def main():" in res.python_source
    assert "    return 0" in res.python_source
    assert 'if __name__ == "__main__":' in res.python_source
    assert "    sys.exit(main())" in res.python_source


def test_codegen_uninitialized_decl_omitted():
    # int x; emits nothing
    res = compile_cxx("int main() { int x; int y = 1; return 0; }")
    assert res.success
    assert "    int x" not in res.python_source
    assert "x = " not in res.python_source
    assert "    y = 1" in res.python_source


def test_codegen_input_prelude_present_when_reading():
    res = compile_cxx("using namespace std; int main() { int x; cin >> x; return 0; }")
    assert res.success
    assert "_tokens = iter(sys.stdin.read().split())" in res.python_source
    assert "x = int(next(_tokens))" in res.python_source


def test_codegen_input_prelude_absent_when_no_reading():
    res = compile_cxx("int main() { int x = 1; return 0; }")
    assert res.success
    assert "_tokens" not in res.python_source


def test_codegen_output_endl_only():
    res = compile_cxx("using namespace std; int main() { cout << endl; return 0; }")
    assert res.success
    assert "    print()" in res.python_source


def test_codegen_output_trailing_endl():
    res = compile_cxx('using namespace std; int main() { cout << "Hello" << endl; return 0; }')
    assert res.success
    assert '    print("Hello")' in res.python_source


def test_codegen_output_no_trailing_endl():
    res = compile_cxx('using namespace std; int main() { cout << 42; return 0; }')
    assert res.success
    assert '    print(42, end="")' in res.python_source


def test_codegen_output_multiple_items():
    res = compile_cxx('using namespace std; int main() { cout << "a" << 1 << "b"; return 0; }')
    assert res.success
    assert '    print("a", 1, "b", sep="", end="")' in res.python_source


def test_codegen_w6001_warning_comment_and_stderr():
    res = compile_cxx("using namespace std; int main() { int a = 10; cout << a / 2 << endl; return 0; }")
    assert res.success
    assert any(w.code == "W6001" for w in res.diagnostics)
    assert "# WARNING W6001" in res.python_source


def test_codegen_name_mangling():
    res = compile_cxx("int main() { int lambda = 1; int print = 2; return 0; }")
    assert res.success
    assert "    lambda_ = 1" in res.python_source
    assert "    print_ = 2" in res.python_source


def test_codegen_compile_builtin():
    # Verify generated source passes Python compile()
    res = compile_cxx("int main() { int a = 1; int b = 2; return 0; }")
    assert res.success
    code = compile(res.python_source, "<string>", "exec")
    assert code is not None
